function switchLang(lang) {
    localStorage.setItem('bts_lang', lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    var lbl = document.getElementById('langLabel');
    if (lbl) lbl.textContent = lang === 'ar' ? 'EN' : 'عربي';
    var t = pageTranslations[lang];
    if (!t) return;
    document.querySelectorAll('[data-i18n]').forEach(function(el) {
        var key = el.getAttribute('data-i18n');
        if (t[key]) el.textContent = t[key];
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el) {
        var key = el.getAttribute('data-i18n-placeholder');
        if (t[key]) el.placeholder = t[key];
    });
}

function initLang() {
    var saved = localStorage.getItem('bts_lang') || 'ar';
    switchLang(saved);
    var btn = document.getElementById('langToggle');
    if (btn) {
        btn.addEventListener('click', function() {
            var current = localStorage.getItem('bts_lang') || 'ar';
            switchLang(current === 'ar' ? 'en' : 'ar');
        });
    }
}

document.addEventListener('DOMContentLoaded', initLang);
